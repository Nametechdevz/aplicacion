export const TYPE_BY_ID: Record<string, ProjectType> = Object.fromEntries(PROJECT_TYPES.map((t) => [t.id, t]));

export function getProjectType(id: string): ProjectType {
  return TYPE_BY_ID[id] ?? TYPE_BY_ID.custom;
}

export function typesByCategory(category: CategoryId): ProjectType[] {
  return PROJECT_TYPES.filter((t) => t.category === category);
}

export function categoryLabel(id: CategoryId): string {
  return CATEGORIES.find((c) => c.id === id)?.label ?? id;
}
