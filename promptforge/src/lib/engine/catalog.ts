/** Construye un grupo de funcionalidades. Un "+" inicial marca la funcionalidad como avanzada. */
function g(name: string, ...items: string[]): FeatureGroup {
  return {
    name,
    items: items.map((raw) =>
      raw.startsWith('+') ? { label: raw.slice(1).trim(), advanced: true } : { label: raw.trim() },
    ),
  };
}

